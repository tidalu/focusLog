import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { format } from 'prettier';

const checkOnly = process.argv.includes('--check');
const openApiPath = resolve('contracts/openapi/focuslog-v1.json');
const websocketPath = resolve('contracts/events/focuslog-ws-v1.schema.json');
const aiMobilePath = resolve('contracts/ai/mobile-ai-v1.json');
const backendRoutesPath = resolve('apps/backend/src/routes/v1.ts');
const gatewayPath = resolve('apps/backend/src/services/websocket-gateway.ts');
const typescriptOutput = resolve('packages/shared-types/src/generated-contracts.ts');
const dartOutput = resolve('apps/mobile/lib/generated/contracts.dart');

const openapi = JSON.parse(readFileSync(openApiPath, 'utf8'));
const websocket = JSON.parse(readFileSync(websocketPath, 'utf8'));
const aiMobile = JSON.parse(readFileSync(aiMobilePath, 'utf8'));
const backendSource = readFileSync(backendRoutesPath, 'utf8');
const gatewaySource = readFileSync(gatewayPath, 'utf8');
const methods = new Set(['get', 'post', 'patch', 'delete', 'put']);
const documented = new Set();
const operations = [];
for (const [path, item] of Object.entries(openapi.paths)) {
  for (const [method, operation] of Object.entries(item)) {
    if (!methods.has(method)) continue;
    documented.add(`${method.toUpperCase()} ${path}`);
    if (!operation.operationId)
      throw new Error(`OpenAPI operation ${method.toUpperCase()} ${path} has no operationId.`);
    operations.push(operation.operationId);
  }
}
const implemented = new Set(
  [...backendSource.matchAll(/app\.(get|post|patch|delete)\(\s*['`]([^'`]+)['`]/g)].map(
    (match) => `${match[1].toUpperCase()} ${match[2].replace(/:([A-Za-z][A-Za-z0-9]*)/g, '{$1}')}`
  )
);
const missing = [...implemented].filter((route) => !documented.has(route));
const stale = [...documented].filter((route) => !implemented.has(route));
if (missing.length || stale.length)
  throw new Error(
    `OpenAPI drift detected. Missing: ${missing.join(', ') || 'none'}. Stale: ${
      stale.join(', ') || 'none'
    }.`
  );

const clientTypes = websocket['x-focuslog-client-message-types'];
const serverTypes = websocket['x-focuslog-server-message-types'];
for (const eventType of [...clientTypes, ...serverTypes])
  if (!gatewaySource.includes(`'${eventType}'`))
    throw new Error(`WebSocket gateway does not implement contracted event ${eventType}.`);

const quotedUnion = (values) => values.map((value) => JSON.stringify(value)).join(' | ');
const constantName = (value) =>
  value.replace(/_([a-z])/g, (_, character) => character.toUpperCase());
const readonlyObject = (value) => JSON.stringify(value, null, 2).replace(/"([^"]+)":/g, '$1:');
const typescriptSource = `// Generated by scripts/generate-contracts.mjs. Do not edit.
export const restApiVersion = ${JSON.stringify(openapi.info.version)} as const;
export const websocketProtocolVersion = '1' as const;
export const aiMobileContractVersion = ${JSON.stringify(aiMobile.schemaVersion)} as const;
export const aiMobileCompatibility = ${readonlyObject(aiMobile.compatibility)} as const;
export const aiMobileJobTypes = ${JSON.stringify(aiMobile.jobTypes, null, 2)} as const;
export type AIMobileJobType = (typeof aiMobileJobTypes)[number];
export const aiMobileJobStatuses = ${JSON.stringify(aiMobile.jobStatuses, null, 2)} as const;
export type AIMobileJobStatus = (typeof aiMobileJobStatuses)[number];
export const aiMobileNormalizedErrors = ${JSON.stringify(aiMobile.normalizedErrors, null, 2)} as const;
export type AIMobileNormalizedError = (typeof aiMobileNormalizedErrors)[number];
export const aiMobilePrivacyModes = ${JSON.stringify(aiMobile.privacyModes, null, 2)} as const;
export type AIMobilePrivacyMode = (typeof aiMobilePrivacyModes)[number];
export const aiMobileProvenanceKinds = ${JSON.stringify(aiMobile.provenanceKinds, null, 2)} as const;
export type AIMobileProvenanceKind = (typeof aiMobileProvenanceKinds)[number];
export const aiMobileExecutionOwnership = ${readonlyObject(aiMobile.executionOwnership)} as const;
export type AIMobileExecutionOwner = (typeof aiMobileExecutionOwnership)[AIMobileJobType];
export const aiMobileMicroUnitPattern = ${JSON.stringify(aiMobile.money.microUnitStringPattern)} as const;
export const aiMobileRedactionForbiddenFields = ${JSON.stringify(aiMobile.redactionForbiddenFields, null, 2)} as const;
export function isReadableAIMobileSchemaVersion(version: number): boolean {
  return Number.isInteger(version) && version >= aiMobileCompatibility.minReadableSchemaVersion && version <= aiMobileCompatibility.maxReadableSchemaVersion;
}
export function aiMobileCompatibilityError(version: number): AIMobileNormalizedError | null {
  if (isReadableAIMobileSchemaVersion(version)) return null;
  return version > aiMobileCompatibility.maxReadableSchemaVersion ? 'READ_ONLY_UNSUPPORTED_AI_SCHEMA' : 'UNSUPPORTED_AI_SCHEMA_VERSION';
}
export interface AIMobileSyncEnvelope {
  readonly schemaVersion: number;
  readonly ownerId: string;
  readonly workspaceId: string;
  readonly origin: 'desktop' | 'android' | 'backend';
  readonly jobType: AIMobileJobType;
  readonly status: AIMobileJobStatus;
  readonly costMicros: string;
  readonly provenance: ReadonlyArray<{ readonly kind: AIMobileProvenanceKind; readonly id: string; readonly revision?: string }>;
}
export const restOperationIds = ${JSON.stringify(operations, null, 2)} as const;
export type RestOperationId = (typeof restOperationIds)[number];
export type ClientWebSocketMessageType = ${quotedUnion(clientTypes)};
export type ServerWebSocketMessageType = ${quotedUnion(serverTypes)};
export interface WebSocketClientFrame<T extends ClientWebSocketMessageType = ClientWebSocketMessageType> {
  readonly version: typeof websocketProtocolVersion;
  readonly type: T;
  readonly requestId: string;
  readonly sentAt: string;
  readonly payload: Readonly<Record<string, unknown>>;
}
export interface WebSocketServerFrame<T extends ServerWebSocketMessageType = ServerWebSocketMessageType> {
  readonly version: typeof websocketProtocolVersion;
  readonly type: T;
  readonly eventId: string;
  readonly requestId?: string;
  readonly sentAt: string;
  readonly payload: Readonly<Record<string, unknown>>;
}
`;
const typescript = await format(typescriptSource, {
  parser: 'typescript',
  singleQuote: true,
  trailingComma: 'none',
  printWidth: 100
});

const dartName = (value) =>
  value.replace(/[.-]([a-z])/g, (_, character) => character.toUpperCase());
const dartAiName = (value) => value.replace(/_([a-z])/g, (_, character) => character.toUpperCase());
const dartStringLiteral = (value) => JSON.stringify(value).replace(/\$/g, '\\$');
const dartEnum = (name, values) => `enum ${name} {
${values.map((value) => `  ${dartName(value)}(${dartStringLiteral(value)})`).join(',\n')};

  const ${name}(this.wireName);
  final String wireName;
}
`;
const dartStringList = (name, values) =>
  `const ${name} = <String>[${values.map((value) => dartStringLiteral(value)).join(', ')}];`;
const dartStringMap = (name, value) =>
  `const ${name} = <String, String>{${Object.entries(value)
    .map(([key, mapValue]) => `${dartStringLiteral(key)}: ${dartStringLiteral(mapValue)}`)
    .join(', ')}};`;
const dartAiEnum = (name, values) => `enum ${name} {
${values.map((value) => `  ${dartAiName(value)}(${dartStringLiteral(value)})`).join(',\n')};

  const ${name}(this.wireName);
  final String wireName;
}
`;
const dart =
  `// Generated by scripts/generate-contracts.mjs. Do not edit.
// ignore_for_file: constant_identifier_names, lines_longer_than_80_chars
const restApiVersion = ${JSON.stringify(openapi.info.version)};
const websocketProtocolVersion = '1';
const aiMobileContractVersion = ${JSON.stringify(aiMobile.schemaVersion)};
const aiMobileMinReadableSchemaVersion = ${JSON.stringify(aiMobile.compatibility.minReadableSchemaVersion)};
const aiMobileMaxReadableSchemaVersion = ${JSON.stringify(aiMobile.compatibility.maxReadableSchemaVersion)};
const aiMobileMicroUnitPattern = ${dartStringLiteral(aiMobile.money.microUnitStringPattern)};

${dartEnum('ClientWebSocketMessageType', clientTypes)}
${dartEnum('ServerWebSocketMessageType', serverTypes)}
${dartAiEnum('AiMobileJobType', aiMobile.jobTypes)}
${dartAiEnum('AiMobileJobStatus', aiMobile.jobStatuses)}
${dartAiEnum('AiMobileNormalizedError', aiMobile.normalizedErrors)}
${dartAiEnum('AiMobilePrivacyMode', aiMobile.privacyModes)}
${dartAiEnum('AiMobileProvenanceKind', aiMobile.provenanceKinds)}
${dartStringList('aiMobileJobTypeWireNames', aiMobile.jobTypes)}
${dartStringList('aiMobileJobStatusWireNames', aiMobile.jobStatuses)}
${dartStringList('aiMobileNormalizedErrorWireNames', aiMobile.normalizedErrors)}
${dartStringList('aiMobilePrivacyModeWireNames', aiMobile.privacyModes)}
${dartStringList('aiMobileProvenanceKindWireNames', aiMobile.provenanceKinds)}
${dartStringMap('aiMobileExecutionOwnership', aiMobile.executionOwnership)}
${dartStringList('aiMobileRedactionForbiddenFields', aiMobile.redactionForbiddenFields)}
bool isReadableAiMobileSchemaVersion(int version) =>
    version >= aiMobileMinReadableSchemaVersion &&
    version <= aiMobileMaxReadableSchemaVersion;
String? aiMobileCompatibilityError(int version) {
  if (isReadableAiMobileSchemaVersion(version)) return null;
  return version > aiMobileMaxReadableSchemaVersion
      ? 'READ_ONLY_UNSUPPORTED_AI_SCHEMA'
      : 'UNSUPPORTED_AI_SCHEMA_VERSION';
}
bool isAiMobileMicroUnitAmount(String value) =>
    RegExp(aiMobileMicroUnitPattern).hasMatch(value);
`.trimEnd() + '\n';

function emit(path, content) {
  if (checkOnly) {
    let current;
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      throw new Error(`Generated contract is missing: ${path}`);
    }
    if (current !== content) throw new Error(`Generated contract is stale: ${path}`);
  } else {
    writeFileSync(path, content);
  }
}

emit(typescriptOutput, typescript);
emit(dartOutput, dart);
console.log(
  `Contract ${checkOnly ? 'verification' : 'generation'} passed: ${documented.size} REST operations, ${clientTypes.length + serverTypes.length} WebSocket messages.`
);
